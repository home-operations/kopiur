/// Render a `Kind:spec.path` for a message: `SnapshotPolicy spec.upload.forceHashPercent`.
pub fn display_spec_path(spec_path: &str) -> String {
    match spec_path.split_once(':') {
        Some((kind, path)) => format!("{kind} {path}"),
        None => spec_path.to_string(),
    }
}
